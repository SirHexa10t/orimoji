#!/usr/bin/env python3
"""Writes src/alphabet/tables.rs: the characters of the two alphabets that no rule of Rust's own can
pick, `two-byte` and `one-cell`. Kept to show where those tables came from. They are FROZEN: text
folded with them must unfold forever, so a later Unicode that would pick differently must not
change them. The test `alphabet::tables::the_tables_are_the_frozen_ones` holds them to that.

Python's `unicodedata` gives categories, bidi classes, widths and normalization; Perl's `\\p{Emoji}`
gives the one property Python lacks. Run: python3 tools/alphabet_tables.py > src/alphabet/tables.rs
"""
import subprocess, sys, unicodedata as ud

def emoji():
    script = 'for my $cp (0..0xFFFF) { next if $cp >= 0xD800 && $cp <= 0xDFFF; print "$cp\\n" if chr($cp) =~ /\\p{Emoji}/ }'
    return {int(line) for line in subprocess.run(["perl", "-e", script], capture_output=True, text=True, check=True).stdout.split()}

EMOJI = emoji()
IGNORABLE = {0x115F, 0x1160, 0x3164, 0xFFA0, 0x180E, 0xFFFC, 0xFFFD}
JAMO = [(0x1100, 0x11FF), (0xA960, 0xA97F), (0xD7B0, 0xD7FF)]

def survives(cp):
    """Text that holds this character keeps it: it takes a cell of its own, is drawn left to right,
    and no normalization, emoji presentation or invisibility changes or hides it."""
    ch = chr(cp)
    return (ud.category(ch)[0] not in "CMZ" and cp not in IGNORABLE and cp not in EMOJI
            and not any(lo <= cp <= hi for lo, hi in JAMO)
            and ud.bidirectional(ch) not in ("R", "AL", "AN") and ud.normalize("NFC", ch) == ch)

# Two-byte: the letters (Lu Ll Lt Lm Lo) of U+0080..U+07FF — 1038 of them under Unicode 16.
two = [chr(cp) for cp in range(0x80, 0x800) if survives(cp) and ud.category(chr(cp))[0] == "L"][:1024 + 4]
# One-cell: everything in U+0800..U+FFFF a terminal draws one cell wide everywhere — not wide, and
# not East Asian "ambiguous" either.
one = [chr(cp) for cp in range(0x800, 0x10000) if survives(cp) and ud.east_asian_width(chr(cp)) in ("N", "Na", "H")][:8192 + 32]
assert len(two) == 1028 and len(one) == 8224, (len(two), len(one))

def rust(name, chars, doc):
    lines = [chars[i:i + 32] for i in range(0, len(chars), 32)]
    body = "\\\n".join(lines)
    return f"{doc}\npub(super) const {name}: &str = \"\\\n{body}\";\n"

print(f"""//! Generated by tools/alphabet_tables.py under Unicode {ud.unidata_version} — and FROZEN since: text
//! folded with these must unfold forever, so they are never regenerated into anything else.
//! Each holds an alphabet's characters in order, then its short set (see `super::sliced`).
""")
print(rust("TWO_BYTE", "".join(two), "/// 1024 letters UTF-8 writes in two bytes, then 4 more for a short last character."))
print(rust("ONE_CELL", "".join(one), "/// 8192 one-cell characters UTF-8 writes in three bytes, then 32 more for a short last character."))
